import math


def area(r):
    """Вычисляет площадь круга.

    Параметры:
        r (float): радиус окружности

    Возвращаемое значение:
        float: площадь круга с радиусом r
    """
    return math.pi * r * r


def perimeter(r):
    """Вычисляет длину окружности.

    Параметры:
        r (float): радиус окружности
    
    Возвращаемое значение:
        float: длина окружности с радиусом r
    """
    return 2 * math.pi * r

